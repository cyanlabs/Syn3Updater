#!/usr/bin/env bash
# Builds a self-contained Linux package: Syn3Updater-<version>-<rid>.tar.gz (+ .sha256).
# usage: scripts/package-linux.sh <linux-x64|linux-arm64> <version> [outdir]
set -euo pipefail
RID="${1:?rid (linux-x64 or linux-arm64)}"; VERSION="${2:?version, e.g. 3.0.0}"; OUT="${3:-artifacts}"
cd "$(dirname "$0")/.."
export PATH="$HOME/.dotnet:$PATH" DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1

NAME="Syn3Updater-$VERSION-$RID"
STAGE="$(mktemp -d)/$NAME"; mkdir -p "$STAGE" "$OUT"

dotnet publish src/Syn3Updater.App -c Release -r "$RID" --self-contained \
  -p:Version="$VERSION" -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -p:DebugType=none -o "$STAGE"

cp src/Syn3Updater.App/Assets/logo.png "$STAGE/syn3updater.png"
cp LICENSE "$STAGE/"

# The launcher entry is generated by install.sh with the real install path. (The archive used to carry a ready-made syn3updater.desktop
# saying "Exec=syn3updater" next to a program called "Syn3Updater": on a case-sensitive file system that entry pointed at nothing.)
cat > "$STAGE/install.sh" <<'INST'
#!/usr/bin/env bash
# Installs Syn3 Updater for the current user (no root needed):
#   ~/.local/share/syn3updater          the program
#   ~/.local/bin/syn3updater            a command (lower case) that starts it
#   ~/.local/share/applications         the launcher entry in your application menu
#   ~/.local/share/icons                its icon
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ ! -f "$here/Syn3Updater" ]]; then
  echo "Syn3Updater was not found next to install.sh. Run this script from inside the extracted folder." >&2; exit 1
fi
data="${XDG_DATA_HOME:-$HOME/.local/share}"; dest="$data/syn3updater"; bin="$HOME/.local/bin"
mkdir -p "$dest" "$bin" "$data/applications" "$data/icons/hicolor/128x128/apps"

install -m 755 "$here/Syn3Updater" "$dest/Syn3Updater"
[[ -f "$here/LICENSE" ]] && install -m 644 "$here/LICENSE" "$dest/LICENSE"
install -m 644 "$here/syn3updater.png" "$data/icons/hicolor/128x128/apps/syn3updater.png"
ln -sf "$dest/Syn3Updater" "$bin/syn3updater"
# tells the app it may update itself in place (it re-runs this install.sh from the new release)
echo tar > "$dest/.install-method"; chmod 644 "$dest/.install-method"

cat > "$data/applications/syn3updater.desktop" <<DESK
[Desktop Entry]
Type=Application
Name=Syn3 Updater
Comment=Ford SYNC 3 update USB creator
Exec="$dest/Syn3Updater" %u
TryExec=$dest/Syn3Updater
Icon=syn3updater
Terminal=false
Categories=Utility;
MimeType=x-scheme-handler/syn3updater;
DESK
chmod 644 "$data/applications/syn3updater.desktop"
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$data/applications" >/dev/null 2>&1 || true
command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -q -t "$data/icons/hicolor" >/dev/null 2>&1 || true
# make syn3updater:// links (from the CyanLabs website and forum) open this app
command -v xdg-mime >/dev/null 2>&1 && xdg-mime default syn3updater.desktop x-scheme-handler/syn3updater >/dev/null 2>&1 || true

echo "Installed to $dest"
echo "Start it from your application menu (Syn3 Updater) or run: $dest/Syn3Updater"
case ":$PATH:" in *":$bin:"*) echo "The command 'syn3updater' also works in a terminal." ;; *) echo "(Add $bin to your PATH to start it with just 'syn3updater'.)" ;; esac

# Preparing a USB stick needs a few system tools. Downloading to a folder does not.
missing=()
for tool in lsblk sfdisk wipefs udisksctl pkexec mkfs.exfat; do command -v "$tool" >/dev/null 2>&1 || missing+=("$tool"); done
if ((${#missing[@]})); then
  ids=" "; if [[ -r /etc/os-release ]]; then ids=" $(. /etc/os-release; echo "${ID:-} ${ID_LIKE:-}") "; fi
  case "$ids" in
    *" fedora "*|*" rhel "*|*" centos "*|*" nobara "*) hint="sudo dnf install exfatprogs udisks2 polkit util-linux" ;;
    *" debian "*|*" ubuntu "*)                          hint="sudo apt install exfatprogs udisks2 policykit-1 util-linux" ;;
    *" arch "*)                                         hint="sudo pacman -S exfatprogs udisks2 polkit util-linux" ;;
    *" suse "*|*" opensuse "*)                          hint="sudo zypper install exfatprogs udisks2 polkit util-linux" ;;
    *)                                                  hint="" ;;
  esac
  echo
  echo "Note: preparing a USB drive also needs: ${missing[*]}"
  [[ -n "$hint" ]] && echo "  Install them with: $hint"
fi
INST

cat > "$STAGE/uninstall.sh" <<'UNINST'
#!/usr/bin/env bash
# Removes what install.sh installed. Your settings and downloads are kept (settings: ~/.local/share/CyanLabs/Syn3Updater).
set -euo pipefail
data="${XDG_DATA_HOME:-$HOME/.local/share}"
rm -rf "$data/syn3updater"
rm -f "$HOME/.local/bin/syn3updater" "$data/applications/syn3updater.desktop" "$data/icons/hicolor/128x128/apps/syn3updater.png"
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$data/applications" >/dev/null 2>&1 || true
[[ -f "${XDG_CONFIG_HOME:-$HOME/.config}/mimeapps.list" ]] && sed -i '/^x-scheme-handler\/syn3updater=/d' "${XDG_CONFIG_HOME:-$HOME/.config}/mimeapps.list" || true
echo "Syn3 Updater was removed."
UNINST

cat > "$STAGE/README.txt" <<README
Syn3 Updater $VERSION ($RID)

Install (recommended, no root needed):
    ./install.sh
This puts the program in ~/.local/share/syn3updater, adds "Syn3 Updater" to your application menu and a
'syn3updater' command to ~/.local/bin. Remove it again with ./uninstall.sh.

Run without installing:
    ./Syn3Updater
(the program file is called Syn3Updater, with a capital S: file names are case-sensitive on Linux)

Making your own launcher entry: use the full path to the program file, for example
    Exec="/home/you/apps/Syn3Updater-$VERSION-$RID/Syn3Updater"

Links that start with syn3updater:// (on the CyanLabs website and forum) open Syn3 Updater and preselect the region, release and maps,
once it has been installed with ./install.sh.

Preparing a USB drive needs: lsblk, sfdisk, wipefs (util-linux), udisksctl (udisks2), pkexec (polkit), mkfs.exfat (exfatprogs).
  Fedora / Nobara:   sudo dnf install exfatprogs udisks2 polkit util-linux
  Debian / Ubuntu:   sudo apt install exfatprogs udisks2 policykit-1 util-linux
  Arch:              sudo pacman -S exfatprogs udisks2 polkit util-linux
Downloading to a folder does not need any of them.
README

chmod +x "$STAGE/install.sh" "$STAGE/uninstall.sh" "$STAGE/Syn3Updater"

tar -C "$(dirname "$STAGE")" -czf "$OUT/$NAME.tar.gz" "$NAME"
( cd "$OUT" && sha256sum "$NAME.tar.gz" > "$NAME.tar.gz.sha256" )
echo "built $OUT/$NAME.tar.gz"
